import json
from config import logger
from sarvamai import SarvamAI

class SchemaTranslator:
    def __init__(self, api_key: str):
        self.client = SarvamAI(api_subscription_key=api_key)

    def translate_to_json(self, raw_text: str) -> str:
        """
        Calls the Sarvam API to translate raw, messy schema text into strict JSON format.
        """
        system_prompt = """
You are an expert Oracle Database Architect and data engineer.
Your task is to take messy, unstructured, raw schema definitions or pseudo-SQL and translate them into a STRICT JSON schema format.

Rules for Translation:
1. Fix typos (e.g. CustermerInfo -> CUSTOMER_INFO).
2. Map standard generic SQL types (BigInt, Smallint, Varchar) to Oracle-compliant types (NUMBER, VARCHAR2, TIMESTAMP, DATE, FLOAT).
3. Extract any Primary Keys into a table-level array called "primary_key_columns": ["col1", "col2"]. Do NOT use inline "primary_key" flags on columns.
4. Extract any indexes into a table-level array called "indexes": [{"name": "IDX_NAME", "columns": ["col1"]}].
5. Intelligently infer and assign logical Faker providers for each column based on its name.
   - For IDs: "random_int" (or if auto-generated, set "auto_generated": true)
   - For Names: "name", "first_name", or "last_name"
   - For Email: "email"
   - For Dates: "date_time", "past_datetime", or "date_between"
   - For Addresses: "address"
   - For Text/Remarks: "sentence" or "word"
6. Ensure Foreign Keys are correctly parsed into a table-level array called "foreign_keys".

Output ONLY valid JSON matching this structure. NO markdown blocks (like ```json). You MUST keep your internal reasoning extremely brief (under 50 words) to avoid hitting token limits. Immediately output the raw JSON object.

Example Output Structure:
{
  "tables": [
    {
      "name": "USERS",
      "columns": [
        {"name": "USER_ID", "type": "NUMBER GENERATED BY DEFAULT AS IDENTITY", "auto_generated": true},
        {"name": "USERNAME", "type": "VARCHAR2(50)", "faker": "user_name"},
        {"name": "CREATED_AT", "type": "TIMESTAMP DEFAULT CURRENT_TIMESTAMP", "faker": "past_datetime"}
      ],
      "primary_key_columns": ["USER_ID"],
      "foreign_keys": [],
      "indexes": []
    }
  ],
  "procedures": [],
  "functions": [],
  "triggers": []
}
"""
        
        try:
            combined_prompt = f"{system_prompt.strip()}\n\n---\nRaw Schema Text to Translate:\n{raw_text}"
            
            response = self.client.chat.completions(
                model="sarvam-105b",
                messages=[
                    {"role": "user", "content": combined_prompt}
                ],
                temperature=0.1,
                max_tokens=4096,
            )
            
            ai_content = response.choices[0].message.content
            if ai_content is None:
                reasoning = getattr(response.choices[0].message, 'reasoning_content', None)
                if reasoning:
                    logger.warning("API returned no content, falling back to parsing reasoning_content")
                    ai_content = reasoning
                else:
                    raise ValueError(f"API returned no content. Full response: {response}")
                
            ai_content = ai_content.strip()
            
            # Extract JSON if there is surrounding text (vital if falling back to reasoning_content)
            start_idx = ai_content.find('{')
            end_idx = ai_content.rfind('}')
            
            if start_idx != -1 and end_idx != -1 and end_idx > start_idx:
                ai_content = ai_content[start_idx:end_idx+1]
            else:
                logger.warning("Could not clearly identify JSON block boundaries in response.")
                
            return ai_content.strip()
            
        except Exception as e:
            logger.error(f"Failed to translate schema: {e}")
            raise Exception(f"AI Translation failed: {e}")
