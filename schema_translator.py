import json
from config import logger
from sarvamai import SarvamAI
import httpx

class SchemaTranslator:
    def __init__(self, api_key: str, dialect: str = "Oracle"):
        self.client = SarvamAI(
            api_subscription_key=api_key, 
            httpx_client=httpx.Client(timeout=300.0)
        )
        self.dialect = dialect

    def translate_to_json(self, raw_text: str) -> str:
        """
        Calls the Sarvam API to translate raw, messy schema text into strict JSON format.
        """
        if self.dialect == "MSSQL":
            type_mapping_rule = "2. Map standard generic SQL types (BigInt, Smallint, Varchar) to MSSQL-compliant types (INT, BIGINT, DECIMAL, VARCHAR, NVARCHAR, DATETIME)."
        elif self.dialect == "PostgreSQL":
            type_mapping_rule = "2. Map standard generic SQL types (BigInt, Smallint, Varchar) to PostgreSQL-compliant types (INT, BIGINT, NUMERIC, VARCHAR, TIMESTAMP, DATE)."
        else: # Oracle
            type_mapping_rule = "2. Map standard generic SQL types (BigInt, Smallint, Varchar) to Oracle-compliant types (NUMBER, VARCHAR2, TIMESTAMP, DATE, FLOAT)."

        system_prompt = f"""
You are an expert {self.dialect} Database Architect and data engineer.
Your task is to take messy, unstructured, raw schema definitions or pseudo-SQL and translate them into a STRICT JSON schema format.

Rules for Translation:
1. Fix typos (e.g. CustermerInfo -> CUSTOMER_INFO).
{type_mapping_rule}
   - If a column is an auto-increment primary key, use the universal cross-dialect syntax: "BIGINT GENERATED BY DEFAULT AS IDENTITY".
3. Extract any Primary Keys into a table-level array called "primary_key_columns": ["col1", "col2"]. Do NOT use inline "primary_key" flags on columns.
4. Extract any indexes into a table-level array called "indexes": [{{"name": "IDX_NAME", "columns": ["col1"]}}].
   - CRITICAL: Index names MUST be totally unique. Do NOT reuse the same name for multiple indexes!
5. Intelligently infer and assign logical Faker providers for each column based on its name and SQL type.
   - For IDs: "random_int" (or if auto-generated, set "auto_generated": true)
   - For Names: "name"
   - For Email: "email"
   - For Dates: "date_time" or "past_datetime"
   - For Addresses: "address"
   - For Text/Remarks: "sentence" or "word" (Do NOT assign random_int to VARCHAR columns)
   - For numeric amounts/balances: "random_float"
6. Ensure Foreign Keys are correctly parsed into a table-level array called "foreign_keys".
   - FORMAT CRITICAL: MUST use singular strings for FK mappings, NOT arrays! Example: {{"column": "COL_NAME", "references_table": "REF_TABLE", "references_column": "REF_COL"}}.

Output ONLY valid JSON matching this structure. You MUST wrap your final JSON in a ```json ... ``` markdown block so it can be extracted programmatically. Keep your reasoning brief.

Example Output Structure:
{{
  "tables": [
    {{
      "name": "USERS",
      "columns": [
        {{"name": "USER_ID", "type": "NUMBER GENERATED BY DEFAULT AS IDENTITY", "auto_generated": true}},
        {{"name": "USERNAME", "type": "VARCHAR2(50)", "faker": "user_name"}},
        {{"name": "CREATED_AT", "type": "TIMESTAMP DEFAULT CURRENT_TIMESTAMP", "faker": "past_datetime"}}
      ],
      "primary_key_columns": ["USER_ID"],
      "foreign_keys": [],
      "indexes": []
    }}
  ],
  "procedures": [],
  "functions": [],
  "triggers": []
}}
"""
        
        import time
        max_retries = 3
        for attempt in range(max_retries):
            try:
                combined_prompt = f"{system_prompt.strip()}\n\n---\nRaw Schema Text to Translate:\n{raw_text}"
                
                response = self.client.chat.completions(
                    model="sarvam-105b",
                    messages=[
                        {"role": "user", "content": combined_prompt}
                    ],
                    temperature=0.1,
                    max_tokens=4096,
                    reasoning_effort="low",
                )
                
                ai_content = response.choices[0].message.content
                if ai_content is None:
                    reasoning = getattr(response.choices[0].message, 'reasoning_content', None)
                    if reasoning:
                        logger.warning("API returned no content, falling back to parsing reasoning_content")
                        ai_content = reasoning
                    else:
                        raise ValueError(f"API returned no content. Full response: {response}")
                    
                ai_content = ai_content.strip()
                
                import re
                
                # 1. Try to extract from ```json ... ``` block
                json_match = re.search(r'```json\s*(.*?)\s*```', ai_content, re.DOTALL)
                if json_match:
                    ai_content = json_match.group(1)
                else:
                    # 2. Try to find the root JSON object by locating the first {"tables":
                    start_idx = ai_content.find('{"tables":')
                    if start_idx == -1:
                        # Fallback to finding the first { containing "tables" with spaces
                        start_idx = ai_content.find('"tables"')
                        if start_idx != -1:
                            start_idx = ai_content.rfind('{', 0, start_idx)
                            
                    if start_idx != -1:
                        end_idx = ai_content.rfind('}')
                        if end_idx > start_idx:
                            ai_content = ai_content[start_idx:end_idx+1]
                    else:
                        # Ultimate fallback
                        start_idx = ai_content.find('{')
                        end_idx = ai_content.rfind('}')
                        if start_idx != -1 and end_idx != -1 and end_idx > start_idx:
                            ai_content = ai_content[start_idx:end_idx+1]
                            
                return ai_content.strip()
                
            except Exception as e:
                logger.error(f"Failed to translate schema (Attempt {attempt+1}/{max_retries}): {e}")
                if attempt == max_retries - 1:
                    raise Exception(f"AI Translation failed after {max_retries} attempts: {e}")
                time.sleep(3)
